// Writes supabase/seed.sql from src/content.js, so the database starts with
// exactly what the site shows today. Run with `npm run db:seed-file` (after
// `npm run images`, which makes the photo sizes this reads).
//
// Product photos are referred to by their place in the public-media bucket
// (`products/<id>`); `npm run db:upload-photos` (phase 2) puts them there.
import { readFileSync, writeFileSync } from 'node:fs'
import * as content from '../src/content.js'

const manifest = JSON.parse(readFileSync(new URL('../src/photo-manifest.json', import.meta.url), 'utf8'))

const q = (s) => `'${String(s).replaceAll("'", "''")}'`
const json = (v) => `${q(JSON.stringify(v))}::jsonb`
const arr = (list) => `array[${list.map(q).join(', ')}]::text[]`
const photoPath = (id) => `products/${id}`

const { brand, houses, houseOf, photos } = content

// Every photo the site shows somewhere. Those not shown (such as cakes with
// customers' names on them) are added as hidden products.
const used = new Set([
  ...content.hero,
  ...content.preloader,
  ...content.chapters.map((c) => c.photo),
  ...content.craft.beats.map((b) => b.photo),
  ...content.statement.photos,
  ...content.bride.photos,
  ...content.ceremony.photos,
  content.ceremony.finale,
  ...content.celebration.ring,
  ...content.home.wall,
  ...content.gallery,
  ...content.process.map((p) => p.photo),
  ...Object.values(houses).flatMap((h) => [h.photo, ...h.sign]),
])

const lines = [
  '-- Generated by scripts/make-seed.mjs from src/content.js. Do not edit by hand.',
  '',
  '-- Site settings',
  `insert into public.site_settings (id, business_name, tagline, whatsapp, email, instagram, seo_title, seo_description)
values (1, ${q(brand.name)}, ${q(brand.tagline)}, ${q(brand.whatsapp)}, ${q(brand.email)}, ${q(brand.instagram)},
  ${q(`${houses.decor.name} & ${houses.cakes.name}: handmade bridal accessories, candles, florals & cakes`)},
  ${q(`${brand.tagline}, made by hand for weddings, Holy Communions, christenings and celebrations.`)})
on conflict (id) do nothing;`,
  '',
  '-- Sections',
]

Object.entries(houses).forEach(([key, h], i) => {
  lines.push(`insert into public.sections (key, name, short_name, named_for, line, enquiry_text, cover_path, aisles, sign_photos, sort)
values (${q(key)}, ${q(h.name)}, ${q(h.short)}, ${q(h.namedFor)}, ${q(h.line)}, ${q(h.enquiry)}, ${q(photoPath(h.photo))},
  ${json(h.sections)}, ${arr(h.sign.map(photoPath))}, ${i})
on conflict (key) do nothing;`)
})

lines.push('', '-- Texts, one block per part of the page')
const blocks = [
  ['chapters', 'Chapters (menu and chapter indicator)', content.chapters],
  ['hero', 'Opening photos', { photos: content.hero }],
  ['preloader', 'Loading screen photos', { photos: content.preloader }],
  ['craft', 'Chapter I: the night before', content.craft],
  ['statement', 'Statement', content.statement],
  ['marquee', 'Moving banner', { items: content.marquee }],
  ['bride', 'Chapter II: the bride', content.bride],
  ['ceremony', 'Chapter III: the ceremony', content.ceremony],
  ['home', 'Chapter IV: the décor', content.home],
  ['celebration', 'Chapter V: the cake', content.celebration],
  ['process', 'How it works', { steps: content.process }],
]
blocks.forEach(([key, label, value], i) => {
  lines.push(`insert into public.content_blocks (key, label, value, sort) values (${q(key)}, ${q(label)}, ${json(value)}, ${i})
on conflict (key) do nothing;`)
})

lines.push('', '-- Products, each with its photo')
Object.entries(photos).forEach(([id, p], i) => {
  const size = manifest[id]
  if (!size) throw new Error(`No photo size for ${id}: run \`npm run images\` first.`)
  lines.push(`insert into public.products (section_key, slug, title, category, is_published, sort)
values (${q(houseOf(id))}, ${q(id)}, ${q(p.title)}, ${q(p.type)}, ${used.has(id)}, ${i})
on conflict (slug) do nothing;
insert into public.product_images (product_id, path, width, height, alt, focus)
select id, ${q(photoPath(id))}, ${size.w}, ${size.h}, ${q(p.alt)}, ${p.focus ? q(p.focus) : 'null'} from public.products where slug = ${q(id)}
on conflict (path) do nothing;`)
})

lines.push('', '-- Gallery, in order')
content.gallery.forEach((id, i) => {
  lines.push(`insert into public.gallery_items (image_id, sort) select id, ${i} from public.product_images where path = ${q(photoPath(id))}
on conflict (image_id) do nothing;`)
})

// Starting choices for the cake inquiry form; the owner edits these and their
// prices in the admin panel.
const cakeOptions = {
  occasion: ['Wedding', 'Birthday', 'Holy Communion', 'Christening', 'Baby shower', 'Anniversary', 'Other'],
  size: ['0.5 kg', '1 kg', '1.5 kg', '2 kg', '3 kg', 'Two tiers', 'Three tiers'],
  base: ['Vanilla', 'Chocolate', 'Red velvet', 'Butterscotch', 'Pineapple', 'Mango', 'Coconut'],
  frosting: ['Whipped cream', 'Buttercream', 'Chocolate ganache', 'Cream cheese', 'Fondant'],
}
lines.push('', '-- Cake inquiry options (starting list, prices to be set by the owner)')
for (const [kind, labels] of Object.entries(cakeOptions)) {
  labels.forEach((label, i) => {
    lines.push(`insert into public.cake_options (kind, label, sort) values (${q(kind)}, ${q(label)}, ${i}) on conflict (kind, label) do nothing;`)
  })
}

const out = new URL('../supabase/seed.sql', import.meta.url)
writeFileSync(out, lines.join('\n') + '\n')
console.log(`Wrote supabase/seed.sql: ${Object.keys(photos).length} products (${[...used].filter((id) => photos[id]).length} shown), ${blocks.length} text blocks.`)
